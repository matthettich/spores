const cache = {};
export function fxPresets(type){
  if (cache[type]) return cache[type];
  const d = fxDefaults(type); if (!Object.keys(d).length) return [];
  return cache[type] = [{name: 'Default', p: d}, ...(FX_PRESETS[type] || []).map(([name, v]) => ({name, p: fxClean(type, Object.assign({}, d, v))}))];
}
export function fxPresetName(type, p){
  const hit = fxPresets(type).find(x => Object.keys(x.p).every(k => x.p[k] === (p ? p[k] : undefined)));
  return hit ? hit.name : null;
}
